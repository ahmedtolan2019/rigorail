import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'
const items = readdirSync('src/shared/ui')
  .filter(
    (name) =>
      name.endsWith('.tsx') &&
      !name.endsWith('.test.tsx') &&
      ![
        'route-feedback.tsx',
        'loading-state.tsx',
        'error-boundary.tsx',
      ].includes(name),
  )
  .sort()
  .map((file) => {
    const source = readFileSync(`src/shared/ui/${file}`, 'utf8'),
      tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true)
    const exports = []
    for (const statement of tree.statements)
      if (
        ts.isExportDeclaration(statement) &&
        statement.exportClause &&
        ts.isNamedExports(statement.exportClause)
      )
        for (const item of statement.exportClause.elements)
          exports.push(item.name.text)
    return {
      name: file.replace('.tsx', ''),
      path: `src/shared/ui/${file}`,
      exports,
      docs: `https://ui.shadcn.com/docs/components/radix/${file.replace('.tsx', '')}`,
    }
  })
const outputs = {
  'src/modules/catalog/components.json': JSON.stringify(items, null, 2) + '\n',
  'docs/component-catalog.md':
    '# Component catalog\n\nGenerated by `npm run catalog` from installed source. Do not edit manually.\nImport individual files. Use the shadcn CLI to add or update registry components.\n\n| Component | Source | Exports |\n| --- | --- | --- |\n' +
    items
      .map(
        (item) =>
          `| [${item.name}](${item.docs}) | [source](../${item.path}) | ${item.exports.join(', ')} |`,
      )
      .join('\n') +
    '\n',
}
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== content)
      throw Error(`${file} is stale. Run npm run catalog.`)
  } else writeFileSync(file, content)
}
console.log(
  `${items.length} installed component entries ${process.argv.includes('--check') ? 'verified' : 'indexed'}.`,
)
